const assert = require('node:assert/strict')
const { mkdtemp, mkdir, readFile, writeFile, rm } = require('node:fs/promises')
const { tmpdir } = require('node:os')
const { join, resolve } = require('node:path')
const { expect } = require('playwright/test')
const { closeElectronTestApplication } = require('./electron-test-close.cjs')

async function verifyUsageMeter(launchApplication) {
  const home = await mkdtemp(join(tmpdir(), 'anas-native-usage-'))
  const output = resolve('tmp/native-usage')
  await mkdir(output, { recursive: true })
  let application
  const errors = []
  try {
    application = await launchApplication(home)
    const page = await application.firstWindow()
    page.setDefaultTimeout(15000)
    page.on('pageerror', error => errors.push(String(error)))
    await page.locator('[data-agent-composer-input]').waitFor()
    assert.equal((await page.evaluate(() => globalThis.gale.plugins.list())).some(plugin => plugin.id === 'usage-meter'), false)
    await application.evaluate(() => {
      globalThis.usageTestCalls = 0
      globalThis.usageBalanceCalls = 0
      globalThis.fetch = async (url, options) => {
        globalThis.usageTestCalls++
        if (url === 'https://business.aliyuncs.com/') {
          globalThis.usageBalanceCalls++
          return Response.json({ Success: true, Code: '200', Data: { Currency: 'CNY', AvailableCashAmount: '12.34', AvailableAmount: '12.34', CreditAmount: '0.00' } })
        }
        if (url.endsWith('/models')) return Response.json({ data: [{ id: 'fixture-model' }] })
        if (url.includes('minimaxi')) return Response.json({ base_resp: { status_code: 0 }, model_remains: [{ model_name: 'general',
          current_interval_remaining_percent: 90, current_weekly_remaining_percent: 99, weekly_boost_permille: 1500, end_time: Date.now() + 3600000, weekly_end_time: Date.now() + 86400000 }] })
        if (url.includes('deepseek')) return Response.json({ is_available: true, balance_infos: [{ currency: 'CNY', total_balance: '12.34', granted_balance: '0', topped_up_balance: '12.34' }] })
        if (url.includes('tencentcloudapi')) return Response.json({ Response: options.headers['X-TC-Action'] === 'DescribeAccountBalance' ? { RealBalance: 1234 } : { TotalStats: { TotalToken: 123 } } })
        if (url.includes('generateAccessToken')) return Response.json({ cliAccessToken: 'fixture-token' })
        if (url.includes('bailian-cs')) return Response.json({ success: false, message: 'BailianGateway.AuthorityPolicies.NoPermission 智能体-操作' })
        throw new Error('Unexpected test URL')
      }
    })
    const selected = await page.evaluate(async () => {
      const api = globalThis.gale
      await api.config.updateSettings({ language: 'zh-CN', theme: 'light' })
      const config = await api.config.saveModelProvider({ name: 'Usage fixture', protocol: 'openai_chat_completions', baseUrl: 'https://api.minimaxi.com/v1', apiKey: 'fixture-key', parameters: {} })
      const providerId = config.providers.at(-1).id
      const saved = await api.config.saveProviderModel({ providerId, displayName: 'Fixture', model: 'fixture-model', parameters: {}, parameterPresetMode: 'none', parameterPresets: [],
        capabilities: { vision: false, toolUse: true }, stream: true, maxContextTokens: 128000, maxOutputTokens: 4096, contextCompressionThreshold: .8, contextCompressionEnabled: false })
      const modelId = saved.providers.at(-1).models[0].id
      await api.config.selectDefaultModel(modelId)
      const workspace = await api.agent.workspace.get()
      await api.agent.workspace.set({ ...workspace, mode: 'new_thread', modelConfigId: modelId, modelParameterPresetId: null })
      return { providerId, modelId }
    })
    await page.reload()
    const meter = page.locator('.usage-meter')
    await expect(meter).toContainText('148.5%')
    const count = await application.evaluate(() => globalThis.usageTestCalls)
    await page.getByRole('button', { name: '展开用量详情', exact: true }).click()
    await expect(meter.locator('progress')).toHaveCount(2)
    await expect.poll(() => page.evaluate(async id => (await globalThis.gale.config.get()).providers.find(p => p.id === id).usage.displayMode, selected.providerId)).toBe('detailed')
    await page.getByRole('button', { name: '收起用量详情', exact: true }).click()
    assert.equal(await application.evaluate(() => globalThis.usageTestCalls), count)
    await meter.locator('[tabindex="0"]').focus()
    await expect(page.getByRole('tooltip')).toContainText('重置时间')
    await page.screenshot({ path: join(output, 'compact-tooltip.png') })
    await page.mouse.move(600, 300)
    await page.evaluate(() => globalThis.gale.config.updateSettings({ sidebarWidth: 220, fontSize: 22 }))
    await expect(meter.locator('[data-short-text]')).toBeVisible()
    await page.screenshot({ path: join(output, 'compact-large-font.png') })
    await page.evaluate(() => globalThis.gale.config.updateSettings({ fontSize: 14, sidebarWidth: 260 }))
    await page.locator('.sidebar-settings').click()
    await page.getByRole('menuitem', { name: '设置', exact: true }).click()
    await page.locator('[data-settings-tab="model"]').click()
    const checkbox = page.getByRole('checkbox', { name: '显示用量信息', exact: true })
    const baseUrl = page.getByPlaceholder('https://...', { exact: true })
    await expect(checkbox).toBeChecked()
    await expect(page.getByRole('button', { name: '用量查询设置', exact: true })).toHaveCount(0)
    await checkbox.uncheck()
    await expect.poll(() => page.evaluate(async id => (await globalThis.gale.config.get()).providers.find(p => p.id === id).usage.enabled, selected.providerId)).toBe(false)
    await baseUrl.fill('https://unsupported.test/v1')
    await baseUrl.press('Tab')
    await expect(checkbox).toBeDisabled()
    await expect(checkbox).not.toBeChecked()
    await baseUrl.fill('https://api.deepseek.com/v1')
    await baseUrl.press('Tab')
    await expect(checkbox).toBeEnabled()
    await expect(checkbox).toBeChecked()
    await checkbox.uncheck()
    await baseUrl.fill('https://api.deepseek.com')
    await baseUrl.press('Tab')
    await expect(checkbox).not.toBeChecked()
    await baseUrl.fill('https://tokenhub.tencentmaas.com/v1')
    await baseUrl.press('Tab')
    await expect(checkbox).toBeChecked()
    await checkbox.uncheck()
    const settings = page.getByRole('button', { name: '用量查询设置', exact: true })
    await expect(settings).toBeEnabled()
    await settings.click()
    await expect(page.getByRole('checkbox', { name: '显示余额', exact: true })).toBeChecked()
    await page.getByRole('checkbox', { name: '显示余额', exact: true }).uncheck()
    await page.getByLabel('SecretId', { exact: true }).fill('fixture-id')
    await page.getByLabel('SecretKey', { exact: true }).fill('fixture-secret')
    await page.getByRole('button', { name: '取消', exact: true }).click()
    await settings.click()
    await expect(page.getByLabel('SecretId', { exact: true })).toHaveValue('')
    await expect(page.getByRole('checkbox', { name: '显示余额', exact: true })).toBeChecked()
    await page.getByRole('checkbox', { name: '显示余额', exact: true }).uncheck()
    await page.getByLabel('SecretId', { exact: true }).fill('fixture-id')
    await page.getByLabel('SecretKey', { exact: true }).fill('fixture-secret')
    await page.getByRole('button', { name: '保存', exact: true }).click()
    await expect.poll(() => page.evaluate(async id => (await globalThis.gale.config.get()).providers.find(p => p.id === id).usage.tencentSecretId, selected.providerId)).toBe('fixture-id')
    await expect.poll(() => page.evaluate(async id => (await globalThis.gale.config.get()).providers.find(p => p.id === id).usage.tencentShowBalance, selected.providerId)).toBe(false)
    await settings.click()
    await expect(page.getByRole('checkbox', { name: '显示余额', exact: true })).not.toBeChecked()
    await page.screenshot({ path: join(output, 'tencent-settings.png') })
    await page.getByRole('button', { name: '取消', exact: true }).click()
    await baseUrl.fill('https://token-plan.cn-beijing.maas.aliyuncs.com/compatible-mode/v1')
    await baseUrl.press('Tab')
    await settings.click()
    const showBalance = page.getByRole('checkbox', { name: '显示余额', exact: true })
    await expect(showBalance).not.toBeChecked()
    assert.equal(await application.evaluate(() => globalThis.usageBalanceCalls), 0)
    await showBalance.check()
    await page.getByLabel('AccessKey ID', { exact: true }).fill('fixture-access-id')
    const secret = page.getByLabel('AccessKey Secret', { exact: true })
    await secret.fill('fixture-access-secret')
    await secret.press('Tab')
    await page.mouse.move(50, 50)
    await expect(secret).toHaveAttribute('type', 'password')
    await secret.hover()
    await expect(secret).toHaveAttribute('type', 'password')
    await secret.focus()
    await expect(secret).toHaveAttribute('type', 'text')
    await secret.press('Tab')
    await expect(secret).toHaveAttribute('type', 'password')
    await page.screenshot({ path: join(output, 'bailian-settings.png') })
    await page.getByRole('button', { name: '保存', exact: true }).click()
    await expect.poll(() => page.evaluate(async id => (await globalThis.gale.config.get()).providers.find(p => p.id === id).usage.bailianAccessKeyId, selected.providerId)).toBe('fixture-access-id')
    await expect.poll(() => page.evaluate(async id => (await globalThis.gale.config.get()).providers.find(p => p.id === id).usage.bailianShowBalance, selected.providerId)).toBe(true)
    await page.evaluate(async id => {
      const p = (await globalThis.gale.config.get()).providers.find(p => p.id === id)
      await globalThis.gale.config.saveModelProvider({ ...p, apiKey: 'sk-sp-fixture-key' })
    }, selected.providerId)
    await page.reload()
    await expect(meter).toContainText('!')
    await expect(meter).toContainText('￥ 12.34')
    await meter.getByRole('button', { name: '展开用量详情', exact: true }).click()
    await expect(meter).toContainText('智能体-操作')
    await page.screenshot({ path: join(output, 'permission-error.png') })
    await meter.getByRole('button', { name: '配置', exact: true }).click()
    await expect(checkbox).toBeVisible()
    await page.evaluate(() => globalThis.gale.config.updateSettings({ fontSize: 22, language: 'en', theme: 'dark' }))
    await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(900, 720))
    await expect(page.getByRole('checkbox', { name: 'Show usage information', exact: true })).toBeVisible()
    await page.screenshot({ path: join(output, 'model-settings-large-font-en.png') })
    const label = page.locator('.usage-key-label')
    assert.ok(await label.evaluate(el => el.scrollWidth <= el.clientWidth + 1), 'Usage controls must fit the API key label row')
    await page.getByRole('button', { name: 'Usage query settings', exact: true }).click()
    await expect(page.getByRole('checkbox', { name: 'Show balance', exact: true })).toBeChecked()
    await expect(page.getByRole('button', { name: 'Save', exact: true })).toBeVisible()
    await page.screenshot({ path: join(output, 'bailian-settings-large-font-en.png') })
    await page.getByRole('button', { name: 'Cancel', exact: true }).click()
    assert.deepEqual(errors, [])
    await closeElectronTestApplication(application)
    application = undefined
    const modelsPath = join(home, 'config/models.json')
    const models = JSON.parse(await readFile(modelsPath, 'utf8'))
    const provider = models.providers.find(item => item.id === selected.providerId)
    provider.base_url = 'https://tokenhub.tencentmaas.com/v1'
    delete provider.usage
    await writeFile(modelsPath, JSON.stringify(models))
    const legacy = join(home, 'db/plugins/usage-meter')
    await mkdir(legacy, { recursive: true })
    await writeFile(join(legacy, 'display.json'), '{damaged fixture')
    await writeFile(join(legacy, 'anas-installation.json'), JSON.stringify({ version: 0, enabled: false }))
    await writeFile(join(legacy, 'anas-settings.json'), JSON.stringify({ version: 0, values: { tencent_secret_id: 'retained-id', tencent_secret_key: 'retained-secret' } }))
    await writeFile(join(legacy, 'native-migration.json'), '{damaged marker')
    application = await launchApplication(home)
    const restarted = await application.firstWindow()
    await expect(restarted.locator('[data-agent-composer-input]')).toBeVisible()
    const native = await restarted.evaluate(async id => (await globalThis.gale.config.get()).providers.find(item => item.id === id), selected.providerId)
    assert.equal(native.usage.enabled, true)
    assert.equal(native.usage.displayMode, 'compact')
    assert.equal(native.usage.tencentSecretId, '')
    assert.equal(native.usage.tencentSecretKey, '')
    assert.equal(native.usage.tencentShowBalance, true)
    assert.equal(await readFile(modelsPath, 'utf8'), JSON.stringify(models))
    await assert.rejects(readFile(join(legacy, 'models-before-native.json')), { code: 'ENOENT' })
    assert.equal((await restarted.evaluate(() => globalThis.gale.plugins.list())).some(plugin => plugin.id === 'usage-meter'), false)
    console.log('Legacy usage isolation passed: damaged plugin files do not affect startup or native defaults, and model configuration is not rewritten.')
    console.log('Native usage Electron checks passed: default/disabled switches, credentials save/cancel/masking, provider-scoped persistence, native quota, tooltip, layout and permission errors.')
  } finally {
    await closeElectronTestApplication(application)
    await rm(home, { recursive: true, force: true })
  }
}
module.exports = { verifyUsageMeter }
