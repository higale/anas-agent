import { act, fireEvent, render, screen, waitFor } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { afterEach, expect, it, vi } from 'vitest'
import { DetailsPopover } from './DetailsPopover'

afterEach(() => vi.useRealTimers())
const fixture = () => render(<><button>Outside</button><DetailsPopover label="Details" text={'Status: Active\nAuto-renew: Off'} /></>)
const advance = (ms: number) => act(() => vi.advanceTimersByTime(ms))

it('delays hover previews without stealing focus and allows moving into the details', () => {
  vi.useFakeTimers()
  fixture()
  screen.getByRole('button', { name: 'Outside' }).focus()
  const trigger = screen.getByRole('button', { name: 'Details' })
  fireEvent.pointerEnter(trigger, { pointerType: 'mouse' })
  advance(200)
  expect(screen.queryByRole('tooltip')).not.toBeInTheDocument()
  fireEvent.pointerLeave(trigger)
  advance(500)
  expect(screen.queryByRole('tooltip')).not.toBeInTheDocument()
  fireEvent.pointerEnter(trigger, { pointerType: 'mouse' })
  advance(450)
  expect(screen.getByRole('tooltip')).toHaveTextContent('Status: Active')
  expect(screen.getByRole('button', { name: 'Outside' })).toHaveFocus()
  fireEvent.pointerLeave(trigger)
  advance(75)
  fireEvent.pointerEnter(screen.getByRole('tooltip'))
  advance(200)
  expect(screen.getByRole('tooltip')).toBeVisible()
  fireEvent.pointerLeave(screen.getByRole('tooltip'))
  advance(150)
  expect(screen.queryByRole('tooltip')).not.toBeInTheDocument()
})

it('pins an existing preview on click and closes on a second click', () => {
  vi.useFakeTimers()
  fixture()
  const trigger = screen.getByRole('button', { name: 'Details' })
  fireEvent.pointerEnter(trigger)
  advance(450)
  expect(screen.getByRole('tooltip')).toBeVisible()
  fireEvent.click(trigger)
  fireEvent.pointerLeave(trigger)
  advance(1000)
  expect(screen.getByRole('dialog', { name: 'Details' })).toHaveTextContent('Auto-renew: Off')
  fireEvent.click(trigger)
  expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
})

it('supports keyboard activation, Escape, and outside clicks', async () => {
  const user = userEvent.setup()
  fixture()
  const trigger = screen.getByRole('button', { name: 'Details' })
  trigger.focus()
  await user.keyboard('{Enter}')
  expect(screen.getByRole('dialog')).toBeVisible()
  await user.keyboard('{Escape}')
  expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  expect(trigger).toHaveFocus()
  await user.keyboard(' ')
  expect(screen.getByRole('dialog')).toBeVisible()
  await user.click(screen.getByRole('button', { name: 'Outside' }))
  await waitFor(() => expect(screen.queryByRole('dialog')).not.toBeInTheDocument())
})

it('does not open disabled details and cancels pending previews on unmount', () => {
  vi.useFakeTimers()
  const { rerender, unmount } = render(<DetailsPopover label="Details" text="Active" disabled />)
  fireEvent.pointerEnter(screen.getByRole('button'))
  advance(500)
  expect(screen.queryByRole('tooltip')).not.toBeInTheDocument()
  rerender(<DetailsPopover label="Details" text="Active" />)
  fireEvent.pointerEnter(screen.getByRole('button'))
  unmount()
  advance(500)
  expect(screen.queryByRole('tooltip')).not.toBeInTheDocument()
})
