import { render, screen, fireEvent, waitFor } from '@testing-library/react'
import { expect, it, vi } from 'vitest'
import { normalizeUsageSettings } from '@shared/usageMeter'
import { UsageSettingsField } from './UsageSettingsField'
vi.mock('react-i18next', () => ({ useTranslation: () => ({ t: (key: string) => key }) }))
it('disables and unchecks unsupported addresses while hiding extra settings', () => {
  render(<UsageSettingsField baseUrl="https://unsupported.test/v1" value={normalizeUsageSettings(undefined, 'https://api.deepseek.com')} onChange={vi.fn()} />)
  expect(screen.getByRole('checkbox')).toBeDisabled()
  expect(screen.getByRole('checkbox')).not.toBeChecked()
  expect(screen.queryByRole('button', { name: 'usage.settings' })).toBeNull()
})
it('allows credentials to be edited while off and only commits on save', async () => {
  const onChange = vi.fn(), url = 'https://tokenhub.tencentmaas.com/v1'
  render(<UsageSettingsField baseUrl={url} value={normalizeUsageSettings({ enabled: false }, url)} onChange={onChange} />)
  fireEvent.click(screen.getByRole('button', { name: 'usage.settings' }))
  expect(screen.getByRole('checkbox', { name: 'usage.show_balance' })).toBeChecked()
  fireEvent.change(screen.getByLabelText('SecretId'), { target: { value: 'fixture' } })
  fireEvent.click(screen.getByRole('checkbox', { name: 'usage.show_balance' }))
  fireEvent.click(screen.getByRole('button', { name: 'common.cancel' }))
  expect(onChange).not.toHaveBeenCalled()
  fireEvent.click(screen.getByRole('button', { name: 'usage.settings' }))
  expect(screen.getByLabelText('SecretId')).toHaveValue('')
  expect(screen.getByRole('checkbox', { name: 'usage.show_balance' })).toBeChecked()
  fireEvent.click(screen.getByRole('checkbox', { name: 'usage.show_balance' }))
  fireEvent.change(screen.getByLabelText('SecretKey'), { target: { value: 'secret-fixture' } })
  fireEvent.click(screen.getByRole('button', { name: 'common.save' }))
  await waitFor(() => expect(onChange).toHaveBeenCalledWith(expect.objectContaining({ enabled: false, tencentSecretKey: 'secret-fixture', tencentShowBalance: false })))
})
it('shows only Bailian credentials and reveals secrets only during input focus', () => {
  const url = 'https://token-plan.cn-beijing.maas.aliyuncs.com/compatible-mode/v1'
  render(<UsageSettingsField baseUrl={url} value={normalizeUsageSettings(undefined, url)} onChange={vi.fn()} />)
  expect(screen.getByRole('checkbox')).toBeChecked()
  fireEvent.click(screen.getByRole('button', { name: 'usage.settings' }))
  expect(screen.queryByLabelText('SecretId')).toBeNull()
  const secret = screen.getByLabelText('AccessKey Secret')
  expect(secret).toHaveAttribute('type', 'password')
  fireEvent.mouseEnter(secret)
  expect(secret).toHaveAttribute('type', 'password')
  fireEvent.focus(secret)
  fireEvent.mouseLeave(secret)
  expect(secret).toHaveAttribute('type', 'text')
  fireEvent.mouseEnter(secret)
  fireEvent.blur(secret)
  expect(secret).toHaveAttribute('type', 'password')
})
it('defaults balance off, discards cancelled edits and saves it with the provider credentials', () => {
  const url = 'https://token-plan.cn-beijing.maas.aliyuncs.com/compatible-mode/v1', onChange = vi.fn()
  render(<UsageSettingsField baseUrl={url} value={normalizeUsageSettings({ enabled: false }, url)} onChange={onChange} />)
  fireEvent.click(screen.getByRole('button', { name: 'usage.settings' }))
  const balance = screen.getByRole('checkbox', { name: 'usage.show_balance' })
  expect(balance).not.toBeChecked()
  fireEvent.click(balance)
  fireEvent.click(screen.getByRole('button', { name: 'common.cancel' }))
  expect(onChange).not.toHaveBeenCalled()
  fireEvent.click(screen.getByRole('button', { name: 'usage.settings' }))
  expect(screen.getByRole('checkbox', { name: 'usage.show_balance' })).not.toBeChecked()
  fireEvent.click(screen.getByRole('checkbox', { name: 'usage.show_balance' }))
  fireEvent.click(screen.getByRole('button', { name: 'common.save' }))
  expect(onChange).toHaveBeenCalledWith(expect.objectContaining({ enabled: false, bailianShowBalance: true }))
})
